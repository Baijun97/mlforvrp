#!/usr/bin/env python3
"""Memory-conscious preparation and XGBoost ranking for VRPTW data.

This script consumes the files generated by generate_training_dataset.py.

Install once:
    python3 -m pip install -U pandas pyarrow scikit-learn xgboost

Prepare instance-level train/valid/test Parquet files:
    python3 vrptw_ranker_pipeline.py prepare \
      --data-dir processed/all_standard_vrptw_v2 \
      --output-dir processed/vrptw_ranker

Train a first, Mac-friendly baseline on instances with <= 200 customers:
    python3 vrptw_ranker_pipeline.py train \
      --prepared-dir processed/vrptw_ranker \
      --output-dir models/xgb_ranker_200 \
      --max-customers 200

The ranking group is decision_id. Splits are made by instance_id, never by
candidate row, which prevents routes from one VRPTW instance leaking across
training and evaluation sets.
"""

from __future__ import annotations

import argparse
import csv
import importlib
import json
import math
import random
import re
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any, Iterable


SPLIT_RATIOS = {"train": 0.8, "valid": 0.1, "test": 0.1}
SPLIT_ORDER = ("train", "valid", "test")


def require(module_name: str, install_name: str | None = None) -> Any:
    try:
        return importlib.import_module(module_name)
    except ImportError as exc:
        package = install_name or module_name
        raise SystemExit(
            f"Missing dependency: {package}. Install with:\n"
            "  python3 -m pip install -U pandas pyarrow scikit-learn xgboost"
        ) from exc


def read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, value: Any) -> None:
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False), encoding="utf-8")


def family_from_name(instance_id: str) -> str:
    """Maps C101/C1_2_1, R201, RC2_10_1 to C1, R2, RC2."""
    match = re.match(r"^(RC|C|R)([12])", instance_id.upper())
    return "".join(match.groups()) if match else "OTHER"


def allocate_counts(n: int) -> dict[str, int]:
    """Largest-remainder 80/10/10 allocation, with training always present."""
    if n <= 0:
        return {name: 0 for name in SPLIT_ORDER}

    raw = {name: n * SPLIT_RATIOS[name] for name in SPLIT_ORDER}
    counts = {name: int(math.floor(raw[name])) for name in SPLIT_ORDER}
    remainder = n - sum(counts.values())
    priority = {"valid": 0, "test": 1, "train": 2}
    ranked = sorted(
        SPLIT_ORDER,
        key=lambda name: (-(raw[name] - counts[name]), priority[name]),
    )
    for name in ranked[:remainder]:
        counts[name] += 1

    if counts["train"] == 0:
        donor = max(("valid", "test"), key=lambda name: counts[name])
        counts[donor] -= 1
        counts["train"] += 1
    return counts


def build_instance_splits(
    instances_csv: Path, seed: int
) -> tuple[list[dict[str, Any]], dict[str, dict[str, Any]]]:
    with instances_csv.open("r", encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.DictReader(handle))
    if not rows:
        raise SystemExit(f"No instances found in {instances_csv}")

    required = {"instance_id", "num_customers"}
    missing = required - set(rows[0])
    if missing:
        raise SystemExit(f"instances.csv is missing columns: {sorted(missing)}")

    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        instance_id = row["instance_id"]
        family = family_from_name(instance_id)
        num_customers = int(float(row["num_customers"]))
        item = {
            "instance_id": instance_id,
            "family": family,
            "num_customers": num_customers,
            "stratum": f"{family}_{num_customers}",
        }
        grouped[item["stratum"]].append(item)

    rng = random.Random(seed)
    manifest: list[dict[str, Any]] = []
    for stratum in sorted(grouped):
        items = sorted(grouped[stratum], key=lambda item: item["instance_id"])
        rng.shuffle(items)
        counts = allocate_counts(len(items))
        offset = 0
        for split in SPLIT_ORDER:
            for item in items[offset : offset + counts[split]]:
                manifest.append({**item, "split": split})
            offset += counts[split]

    manifest.sort(key=lambda item: item["instance_id"])
    lookup = {item["instance_id"]: item for item in manifest}
    if len(lookup) != len(manifest):
        raise SystemExit("Duplicate instance_id values found in instances.csv")
    return manifest, lookup


def write_manifest(path: Path, manifest: list[dict[str, Any]]) -> None:
    fields = ["instance_id", "family", "num_customers", "stratum", "split"]
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(manifest)


def prepare_command(args: argparse.Namespace) -> None:
    pa = require("pyarrow")
    pacsv = require("pyarrow.csv")
    pc = require("pyarrow.compute")
    pq = require("pyarrow.parquet")

    data_dir = args.data_dir.expanduser().resolve()
    output_dir = args.output_dir.expanduser().resolve()
    candidate_csv = data_dir / "candidate_decisions.csv"
    instances_csv = data_dir / "instances.csv"
    feature_spec = data_dir / "feature_columns.json"
    for path in (candidate_csv, instances_csv, feature_spec):
        if not path.is_file():
            raise SystemExit(f"Required file not found: {path}")

    output_dir.mkdir(parents=True, exist_ok=True)
    manifest, lookup = build_instance_splits(instances_csv, args.seed)
    write_manifest(output_dir / "instance_splits.csv", manifest)
    (output_dir / "feature_columns.json").write_text(
        feature_spec.read_text(encoding="utf-8"), encoding="utf-8"
    )

    split_counts = Counter(item["split"] for item in manifest)
    print(
        "Instance split: "
        + ", ".join(f"{name}={split_counts[name]}" for name in SPLIT_ORDER),
        flush=True,
    )

    read_options = pacsv.ReadOptions(
        block_size=args.block_size_mb * 1024 * 1024,
        use_threads=True,
    )
    reader = pacsv.open_csv(candidate_csv, read_options=read_options)
    writers: dict[str, Any] = {}
    output_paths = {name: output_dir / f"{name}.parquet" for name in SPLIT_ORDER}
    row_counts = Counter()
    positive_counts = Counter()
    started = time.monotonic()

    try:
        for batch_number, batch in enumerate(reader, start=1):
            table = pa.Table.from_batches([batch])
            ids = table.column("instance_id").to_pylist()
            unknown = sorted({value for value in ids if value not in lookup})
            if unknown:
                raise SystemExit(
                    "candidate_decisions.csv contains instance_id values absent from "
                    f"instances.csv, for example: {unknown[:5]}"
                )

            table = table.append_column(
                "split", pa.array([lookup[value]["split"] for value in ids])
            )
            table = table.append_column(
                "num_customers",
                pa.array([lookup[value]["num_customers"] for value in ids], type=pa.int32()),
            )
            table = table.append_column(
                "family", pa.array([lookup[value]["family"] for value in ids])
            )

            for split in SPLIT_ORDER:
                selected = table.filter(pc.equal(table.column("split"), split))
                if selected.num_rows == 0:
                    continue
                selected = selected.drop(["split"])
                if split not in writers:
                    writers[split] = pq.ParquetWriter(
                        output_paths[split],
                        selected.schema,
                        compression=args.compression,
                        use_dictionary=True,
                    )
                writers[split].write_table(selected, row_group_size=args.row_group_size)
                row_counts[split] += selected.num_rows
                positive_counts[split] += int(pc.sum(selected.column("label")).as_py())

            if batch_number == 1 or batch_number % 10 == 0:
                elapsed = time.monotonic() - started
                total_rows = sum(row_counts.values())
                print(
                    f"[batch {batch_number}] rows={total_rows:,}, elapsed={elapsed:.1f}s",
                    flush=True,
                )
    finally:
        for writer in writers.values():
            writer.close()

    missing_outputs = [name for name in SPLIT_ORDER if name not in writers]
    if missing_outputs:
        raise SystemExit(
            "One or more splits contain no candidate rows: " + ", ".join(missing_outputs)
        )

    report = {
        "source_data_dir": str(data_dir),
        "output_dir": str(output_dir),
        "seed": args.seed,
        "ratios": SPLIT_RATIOS,
        "compression": args.compression,
        "instances": {name: split_counts[name] for name in SPLIT_ORDER},
        "candidate_rows": {name: row_counts[name] for name in SPLIT_ORDER},
        "positive_rows": {name: positive_counts[name] for name in SPLIT_ORDER},
    }
    write_json(output_dir / "prepare_report.json", report)
    print(json.dumps(report, indent=2, ensure_ascii=False))


def load_split(
    path: Path,
    features: list[str],
    max_customers: int,
    split_name: str,
) -> tuple[Any, Any, Any, Any]:
    pd = require("pandas")
    columns = list(dict.fromkeys(
        ["decision_id", "label", "candidate_is_depot", "instance_id", "num_customers"]
        + features
    ))
    filters = None
    if max_customers > 0:
        filters = [("num_customers", "<=", max_customers)]
    print(f"Loading {split_name}: {path.name}", flush=True)
    frame = pd.read_parquet(path, columns=columns, filters=filters, engine="pyarrow")
    if frame.empty:
        raise SystemExit(
            f"{split_name} has no rows after --max-customers={max_customers}."
        )

    group_sizes = frame["decision_id"].value_counts(sort=False)
    useful_groups = group_sizes[group_sizes >= 2].index
    removed_rows = int((~frame["decision_id"].isin(useful_groups)).sum())
    frame = frame[frame["decision_id"].isin(useful_groups)].copy()
    frame.sort_values(["decision_id", "candidate_customer_id"] if "candidate_customer_id" in frame else ["decision_id"], inplace=True)
    frame.reset_index(drop=True, inplace=True)

    for column in features:
        frame[column] = pd.to_numeric(frame[column], errors="raise").astype("float32")
    labels = frame["label"].astype("uint8").to_numpy()
    qid, uniques = pd.factorize(frame["decision_id"], sort=False)
    if len(uniques) == 0:
        raise SystemExit(f"{split_name} has no ranking groups with at least 2 candidates")
    if (qid[1:] < qid[:-1]).any():
        raise RuntimeError(f"{split_name} qid is not sorted")

    print(
        f"  {len(frame):,} rows, {len(uniques):,} groups, "
        f"{frame['instance_id'].nunique():,} instances, removed {removed_rows:,} trivial rows",
        flush=True,
    )
    return frame, frame[features], labels, qid.astype("int32", copy=False)


def ranking_metrics(frame: Any, predictions: Any) -> dict[str, Any]:
    np = require("numpy")
    scored = frame[["decision_id", "label", "candidate_is_depot"]].copy()
    scored["prediction"] = predictions
    scored.sort_values(
        ["decision_id", "prediction"], ascending=[True, False], inplace=True
    )

    ranks: list[int] = []
    positive_is_depot: list[bool] = []
    for _, group in scored.groupby("decision_id", sort=False, observed=True):
        positive_positions = np.flatnonzero(group["label"].to_numpy() == 1)
        if len(positive_positions) != 1:
            continue
        rank = int(positive_positions[0]) + 1
        ranks.append(rank)
        positive_is_depot.append(bool(group.iloc[positive_positions[0]]["candidate_is_depot"]))

    ranks_array = np.asarray(ranks, dtype="int32")
    depot_array = np.asarray(positive_is_depot, dtype=bool)

    def summarize(mask: Any) -> dict[str, Any]:
        selected = ranks_array[mask]
        if len(selected) == 0:
            return {"groups": 0, "top1": None, "top3": None, "mrr": None, "ndcg_at_5": None}
        ndcg5 = np.where(selected <= 5, 1.0 / np.log2(selected + 1.0), 0.0)
        return {
            "groups": int(len(selected)),
            "top1": float(np.mean(selected <= 1)),
            "top3": float(np.mean(selected <= 3)),
            "mrr": float(np.mean(1.0 / selected)),
            "ndcg_at_5": float(np.mean(ndcg5)),
        }

    return {
        "all": summarize(np.ones(len(ranks_array), dtype=bool)),
        "customer_next": summarize(~depot_array),
        "route_end_depot": summarize(depot_array),
    }


def train_command(args: argparse.Namespace) -> None:
    np = require("numpy")
    require("pyarrow")
    require("pandas")
    xgb = require("xgboost")

    prepared_dir = args.prepared_dir.expanduser().resolve()
    output_dir = args.output_dir.expanduser().resolve()
    feature_path = prepared_dir / "feature_columns.json"
    split_paths = {name: prepared_dir / f"{name}.parquet" for name in SPLIT_ORDER}
    for path in (feature_path, *split_paths.values()):
        if not path.is_file():
            raise SystemExit(f"Required prepared file not found: {path}")

    spec = read_json(feature_path)
    features = list(spec["features"])
    required_sort_feature = "candidate_customer_id"
    # This identifier is used only for deterministic ordering, never as a feature.
    if required_sort_feature not in features:
        pass

    train_frame, x_train, y_train, qid_train = load_split(
        split_paths["train"], features, args.max_customers, "train"
    )
    valid_frame, x_valid, y_valid, qid_valid = load_split(
        split_paths["valid"], features, args.max_customers, "valid"
    )
    test_frame, x_test, y_test, qid_test = load_split(
        split_paths["test"], features, args.max_customers, "test"
    )

    model = xgb.XGBRanker(
        objective="rank:pairwise",
        eval_metric="ndcg@5",
        n_estimators=args.n_estimators,
        learning_rate=args.learning_rate,
        max_depth=args.max_depth,
        min_child_weight=args.min_child_weight,
        subsample=args.subsample,
        colsample_bytree=args.colsample_bytree,
        reg_lambda=args.reg_lambda,
        tree_method="hist",
        random_state=args.seed,
        n_jobs=args.n_jobs,
        early_stopping_rounds=args.early_stopping_rounds,
    )
    print("Training XGBRanker (rank:pairwise)...", flush=True)
    started = time.monotonic()
    model.fit(
        x_train,
        y_train,
        qid=qid_train,
        eval_set=[(x_valid, y_valid)],
        eval_qid=[qid_valid],
        verbose=args.verbose_eval,
    )
    training_seconds = time.monotonic() - started

    valid_predictions = model.predict(x_valid)
    test_predictions = model.predict(x_test)
    metrics = {
        "model": "XGBRanker",
        "objective": "rank:pairwise",
        "max_customers": args.max_customers if args.max_customers > 0 else None,
        "num_features": len(features),
        "best_iteration": int(getattr(model, "best_iteration", args.n_estimators - 1)),
        "training_seconds": training_seconds,
        "rows": {
            "train": int(len(train_frame)),
            "valid": int(len(valid_frame)),
            "test": int(len(test_frame)),
        },
        "instances": {
            "train": int(train_frame["instance_id"].nunique()),
            "valid": int(valid_frame["instance_id"].nunique()),
            "test": int(test_frame["instance_id"].nunique()),
        },
        "valid": ranking_metrics(valid_frame, valid_predictions),
        "test": ranking_metrics(test_frame, test_predictions),
    }

    output_dir.mkdir(parents=True, exist_ok=True)
    model.save_model(output_dir / "xgboost_ranker.json")
    write_json(output_dir / "metrics.json", metrics)
    write_json(output_dir / "feature_columns.json", spec)

    importance = sorted(
        model.get_booster().get_score(importance_type="gain").items(),
        key=lambda item: item[1],
        reverse=True,
    )
    with (output_dir / "feature_importance_gain.csv").open(
        "w", encoding="utf-8", newline=""
    ) as handle:
        writer = csv.writer(handle)
        writer.writerow(["feature", "gain"])
        writer.writerows(importance)

    print(json.dumps(metrics, indent=2, ensure_ascii=False))
    print(f"Saved model and metrics to {output_dir}")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Prepare and train a leakage-safe VRPTW candidate ranker."
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    prepare = subparsers.add_parser(
        "prepare", help="Stream CSV into instance-level train/valid/test Parquet files."
    )
    prepare.add_argument("--data-dir", type=Path, required=True)
    prepare.add_argument("--output-dir", type=Path, required=True)
    prepare.add_argument("--seed", type=int, default=42)
    prepare.add_argument("--block-size-mb", type=int, default=32)
    prepare.add_argument("--row-group-size", type=int, default=100_000)
    prepare.add_argument(
        "--compression", choices=("zstd", "snappy", "gzip"), default="zstd"
    )
    prepare.set_defaults(func=prepare_command)

    train = subparsers.add_parser(
        "train", help="Train and evaluate an XGBoost pairwise ranker."
    )
    train.add_argument("--prepared-dir", type=Path, required=True)
    train.add_argument("--output-dir", type=Path, required=True)
    train.add_argument(
        "--max-customers",
        type=int,
        default=200,
        help="Use instances up to this size; pass 0 for all sizes.",
    )
    train.add_argument("--n-estimators", type=int, default=1200)
    train.add_argument("--learning-rate", type=float, default=0.05)
    train.add_argument("--max-depth", type=int, default=8)
    train.add_argument("--min-child-weight", type=float, default=1.0)
    train.add_argument("--subsample", type=float, default=0.8)
    train.add_argument("--colsample-bytree", type=float, default=0.8)
    train.add_argument("--reg-lambda", type=float, default=1.0)
    train.add_argument("--early-stopping-rounds", type=int, default=80)
    train.add_argument("--seed", type=int, default=42)
    train.add_argument("--n-jobs", type=int, default=-1)
    train.add_argument("--verbose-eval", type=int, default=25)
    train.set_defaults(func=train_command)
    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
